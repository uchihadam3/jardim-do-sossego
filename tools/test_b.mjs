import { createRequire } from 'module'; const { chromium } = createRequire(import.meta.url)('playwright');
const SP = process.argv[2];
const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
p.on('console', (m) => { if (m.type() === 'error') console.log('[error]', m.text().slice(0, 300)); });
p.on('pageerror', (e) => console.log('[pageerror]', e.message, (e.stack || '').split('\n').slice(0, 4).join(' | ')));
await p.goto('http://localhost:8765/local.html?q=baixa&nointro=1&speed=3&season=2');
await p.waitForFunction(() => window.__ready, null, { timeout: 300000 });
await p.click('#start'); await p.waitForTimeout(2500);
console.log('species', await p.evaluate(() => Object.keys(window.__game.game.sys.hybrids).length));
await p.evaluate(() => { const g = window.__game, S = g.state; S.zones = [0, 7]; g.world.setZone(7, true); g.world.mowZone(7); S.xp = 3000;
  S.plants[0] = { sp: 'margarida', seed: 3, grown: 99999, wet: 5000, giftT: 0, ready: true }; S.plants[1] = { sp: 'amor_perfeito', seed: 4, grown: 99999, wet: 5000, giftT: 0, ready: false };
  S.stats.blooms = 2; S.stats.collected = 2; Math.random = () => 0.01; g.game.tapSpot(g.world.spots[0]); });
await p.waitForTimeout(14000);
console.log('rare', await p.evaluate(() => JSON.stringify(window.__game.state.rare)));
await p.screenshot({ path: SP + '/b1_seed.png' });
await p.evaluate(() => { const g = window.__game; g.game.tapSpot(g.world.spots[0]); });
await p.waitForTimeout(12000);
console.log('hybrids', await p.evaluate(() => JSON.stringify(window.__game.state.hybrids)));
await p.screenshot({ path: SP + '/b2_rare.png' });
await p.evaluate(() => window.__game.ui.closeModal());
await p.evaluate(() => window.__game.ui.album('raras')); await p.waitForTimeout(500); await p.screenshot({ path: SP + '/b3_raras.png' });
await p.evaluate(() => window.__game.ui.closeModal()); await p.click('#season'); await p.waitForTimeout(500); await p.screenshot({ path: SP + '/b4_season.png' }); await p.evaluate(() => window.__game.ui.closeModal());
const veg = await p.evaluate(() => { const g = window.__game; const s = g.world.spots.find((x) => x.type === 'veg'); g.game.tapSpot(s); return s.id; });
await p.waitForTimeout(700); await p.screenshot({ path: SP + '/b5_vegpicker.png' });
await b.close();
