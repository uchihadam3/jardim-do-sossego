import * as THREE from 'three';
import { SPECIES_LIST, buildPlantGeometry, plantMaterialFor } from '../src/species.js';
import { windU } from '../src/plantmat.js';
const q = new URLSearchParams(location.search);
const stage = +(q.get('stage') ?? 4), ids = q.get('ids')?.split(','), big = q.get('big');
const r = new THREE.WebGLRenderer({ antialias: true, preserveDrawingBuffer: true });
r.setSize(innerWidth, innerHeight); r.setPixelRatio(1); document.body.appendChild(r.domElement);
r.toneMapping = THREE.ACESFilmicToneMapping; r.shadowMap.enabled = true; r.shadowMap.type = THREE.PCFSoftShadowMap;
const sc = new THREE.Scene(); sc.background = new THREE.Color(0xcfe3ee);
sc.add(new THREE.HemisphereLight(0xdfeeff, 0x8a7a5a, 1.3));
const sun = new THREE.DirectionalLight(0xfff0d8, 2.6); sun.position.set(4, 8, 5); sun.castShadow = true; sun.shadow.mapSize.set(4096, 4096);
const s = sun.shadow.camera; s.left = -12; s.right = 12; s.top = 12; s.bottom = -12; sun.shadow.bias = -0.0005; sc.add(sun);
const g = new THREE.Mesh(new THREE.PlaneGeometry(60, 60), new THREE.MeshStandardMaterial({ color: 0x6b5a48, roughness: 1 })); g.rotation.x = -Math.PI / 2; g.receiveShadow = true; sc.add(g);
const list = SPECIES_LIST.filter((d) => (ids ? ids.includes(d.id) : big ? (d.tree || d.climber) : !(d.tree || d.climber)));
const cols = +(q.get('cols') ?? (big ? 5 : 8)), sp = big ? 3.4 : 0.95;
let tris = 0;
list.forEach((d, i) => {
  const t0 = performance.now();
  const m = new THREE.Mesh(buildPlantGeometry(d.id, 7 + i, stage), plantMaterialFor(d.id));
  m.castShadow = m.receiveShadow = true;
  const x = (i % cols - (cols - 1) / 2) * sp, z = (Math.floor(i / cols)) * sp * 1.0;
  m.position.set(x, 0, z); sc.add(m); tris += m.geometry.index.count / 3;
  console.log(d.id, m.geometry.index.count / 3, (performance.now() - t0).toFixed(1) + 'ms');
});
const rows = Math.ceil(list.length / cols);
const cam = new THREE.PerspectiveCamera(big ? 34 : 30, innerWidth / innerHeight, 0.1, 200);
const cz = (rows - 1) * sp / 2, dist = +(q.get('dist') ?? (big ? 17 : 8.2)), pitch = +(q.get('pitch') ?? 0.7);
cam.position.set(+(q.get('cx') ?? 0), Math.sin(pitch) * dist + (big ? 1.5 : 0.2), cz + Math.cos(pitch) * dist); cam.lookAt(+(q.get('cx') ?? 0), big ? 1.4 : 0.2, cz + +(q.get('lz') ?? 0));
console.log('TOTAL tris', tris);
let f = 0; (function loop() { windU.uTime.value = performance.now() / 1000; r.render(sc, cam); if (++f === 3) { document.title = 'ready'; return; } requestAnimationFrame(loop); })();
